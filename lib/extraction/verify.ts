import { ExtractedItem } from "@/lib/llm/provider";

export interface ItemSource {
  page_id?: string;
  page_no?: number;
  quote: string; // EXACT verbatim quote from that page
  confidence?: number;
  verified?: boolean;
}

export interface VerifiedItem extends ExtractedItem {
  verified: boolean;
  status: "extracted" | "needs_review";
  sources?: ItemSource[];
}

export interface VerificationResult {
  items: VerifiedItem[];
  stats: {
    total: number;
    verified: number;
    unverified: number;
    verificationRate: number; // 0 to 1
  };
}

/**
 * Normalizes text for lenient quote matching by collapsing whitespace and punctuation variations
 */
function cleanForSearch(text: string): string {
  return text
    .toLowerCase()
    .replace(/[\r\n\t]+/g, " ")
    .replace(/[^\w\s]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Phase 3 Gate: Verify every extracted item's quote against the page's OCR text.
 * Rule 1: Every extracted item must include an exact quote. Verify the quote
 * appears in that page's OCR text; otherwise reject it or set status needs_review.
 * Never show unverified items as facts.
 *
 * ⚠️ CRITICAL CLINICAL LIMITATION & SAFETY NOTE:
 * When OCR text is generated by the same vision model call that extracts items,
 * this gate catches hallucinations and invented items, but DOES NOT catch optical
 * misreads (e.g. if the vision model misreads "Metformin 500 mg" as "50 mg", the quote
 * matches its own transcript and passes this gate).
 *
 * Safety mitigations:
 * 1. Items always start in 'extracted' status; never 'confirmed' without human review.
 * 2. The DocumentViewer highlights quotes directly beside the original page image so the
 *    patient/caregiver visually verifies the physical scan.
 * 3. The evaluation harness (scripts/eval-extractor.ts) cross-checks against independent
 *    ground-truth data to measure real recall and precision.
 */
export function verifyQuotesAgainstOcr(
  items: ExtractedItem[],
  ocrText: string
): VerificationResult {
  if (!ocrText || items.length === 0) {
    return {
      items: items.map((item) => ({
        ...item,
        verified: false,
        status: "needs_review",
      })),
      stats: {
        total: items.length,
        verified: 0,
        unverified: items.length,
        verificationRate: 0,
      },
    };
  }

  const cleanOcr = cleanForSearch(ocrText);
  let verifiedCount = 0;

  const verifiedItems: VerifiedItem[] = items.map((item) => {
    if (!item.quote || item.quote.trim() === "") {
      return {
        ...item,
        verified: false,
        status: "needs_review",
      };
    }

    // 1. Direct verbatim substring match
    const exactMatch = ocrText.includes(item.quote);

    // 2. Case-insensitive / whitespace-normalized fallback
    const cleanQuote = cleanForSearch(item.quote);
    const normalizedMatch = cleanQuote.length > 0 && cleanOcr.includes(cleanQuote);

    const isVerified = exactMatch || normalizedMatch;

    if (isVerified) {
      verifiedCount++;
      return {
        ...item,
        verified: true,
        // Rule 2: New items start as status 'extracted'. Only user action sets 'confirmed'.
        status: "extracted",
      };
    } else {
      return {
        ...item,
        verified: false,
        // Rule 1: if quote does not appear in OCR text, set status needs_review
        status: "needs_review",
      };
    }
  });

  return {
    items: verifiedItems,
    stats: {
      total: items.length,
      verified: verifiedCount,
      unverified: items.length - verifiedCount,
      verificationRate: items.length > 0 ? verifiedCount / items.length : 1,
    },
  };
}

/**
 * Extracts numeric dose tokens (e.g., '500mg', '1000 mg', '10 units', '2 puffs', '40mg')
 * to ensure different strengths/doses are never collapsed into one.
 */
export function extractDoseSignature(text: string): string {
  const doseRegex = /\b(\d+(?:\.\d+)?\s*(?:mg|mcg|g|ml|units?|puffs?|tab|tabs?|caps?|drops?|meq|iu|%))\b/gi;
  const matches = text.match(doseRegex);
  if (!matches || matches.length === 0) return "";
  return matches.map((m) => cleanForSearch(m)).sort().join("-");
}

/**
 * Normalizes condition text by removing ICD codes like (ICD-10: E11.9)
 * so coded and uncoded mentions merge smoothly.
 */
export function normalizeConditionForMerge(text: string): string {
  return cleanForSearch(
    text
      .replace(/\s*\(\s*icd(?:-?\d+)?\s*:[^)]+\)/gi, "")
      .replace(/\s*\(\s*icd[^)]+\)/gi, "")
  );
}

/**
 * Computes a deduplication key for an item:
 * - Medications: category + drug name + dose signature (so 500mg vs 1000mg stay separate)
 * - Conditions: category + condition without ICD codes
 * - Other: category + clean value
 */
export function getItemDeduplicationKey(category: string, value: string): string {
  const cat = category.toLowerCase().trim();
  if (cat === "medication") {
    const dose = extractDoseSignature(value);
    const nameWithoutDose = cleanForSearch(
      value.replace(/\b(\d+(?:\.\d+)?\s*(?:mg|mcg|g|ml|units?|puffs?|tab|tabs?|caps?|drops?|meq|iu|%))\b/gi, "")
    );
    return `medication:${nameWithoutDose}:${dose}`;
  }
  if (cat === "condition") {
    return `condition:${normalizeConditionForMerge(value)}`;
  }
  return `${cat}:${cleanForSearch(value)}`;
}

/**
 * Deduplicate extracted items:
 * Merges items within the same category that share the same normalized value.
 * - Stores all supporting quotes and pages in a `sources` list (NEVER joined with " | ")
 * - Keeps primary `quote` as a single verbatim string so it continues to verify and highlight
 * - Keeps different doses separate (Metformin 500mg vs 1000mg)
 * - Merges condition ICD variants (e.g. "Type 2 Diabetes Mellitus (ICD-10: E11.9)" and plain)
 * - Retains highest confidence score
 * - Flags as 'needs_review' if any instance was unverified
 */
export function deduplicateExtractedItems<
  T extends {
    category: string;
    value: string;
    quote?: string;
    page_no?: number;
    page_id?: string;
    confidence?: number;
    box_2d?: [number, number, number, number];
    status?: string;
    verified?: boolean;
    normalization_source?: string;
    sources?: ItemSource[];
  }
>(items: T[]): (T & { sources: ItemSource[] })[] {
  const map = new Map<string, T & { sources: ItemSource[] }>();

  for (const item of items) {
    const key = getItemDeduplicationKey(item.category, item.value);
    const existing = map.get(key);

    const sourceEntry: ItemSource = {
      page_id: item.page_id,
      page_no: item.page_no,
      quote: item.quote || "",
      confidence: item.confidence,
      verified: item.verified,
    };

    if (!existing) {
      map.set(key, {
        ...item,
        quote: item.quote || "",
        sources: item.quote ? [sourceEntry] : [],
      });
    } else {
      // Append to sources list if not already present
      if (item.quote) {
        const cleanItemQuote = cleanForSearch(item.quote);
        const alreadyHasQuote = existing.sources.some(
          (s) => cleanForSearch(s.quote) === cleanItemQuote && s.page_no === item.page_no
        );
        if (!alreadyHasQuote) {
          existing.sources.push(sourceEntry);
        }
      }

      // Condition title: prefer cleaner plain title if existing had ICD code
      if (item.category === "condition") {
        const existingHasIcd = /icd/i.test(existing.value);
        const itemHasIcd = /icd/i.test(item.value);
        if (existingHasIcd && !itemHasIcd) {
          existing.value = item.value;
        }
      }

      // Confidence: take highest
      if (typeof item.confidence === "number") {
        existing.confidence = Math.max(existing.confidence ?? 0, item.confidence);
      }

      // Primary quote: choose the most specific / longest verbatim quote from sources (NEVER join with " | ")
      if (item.quote && existing.quote) {
        if (item.quote.length > existing.quote.length) {
          existing.quote = item.quote;
        }
      } else if (item.quote && !existing.quote) {
        existing.quote = item.quote;
      }

      // Safety: If any instance was unverified / needs_review, the merged item remains needs_review
      if (item.status === "needs_review" || existing.status === "needs_review") {
        existing.status = "needs_review";
        if ("verified" in existing) {
          (existing as any).verified = false;
        }
      }

      // Normalization source: prefer non-'none'
      if (
        existing.normalization_source === "none" &&
        item.normalization_source &&
        item.normalization_source !== "none"
      ) {
        existing.normalization_source = item.normalization_source;
      }
    }
  }

  return Array.from(map.values());
}

